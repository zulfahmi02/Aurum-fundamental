const assert = require('node:assert/strict');
const { appendManual, readManual, selectManual, manualSummary, validSource, MANUAL_KEY } = require('../.test-build/manual.js');
const { createSnapshot, readHistory, reviewFundamentals } = require('../.test-build/review.js');
const { parseBackup } = require('../.test-build/backup.js');
const { restoreLocal } = require('../.test-build/localBackup.js');
const release = Date.parse('2026-11-06T13:30:00Z');
const cutoff = release - 5*60000;
const publishedAt = Date.parse('2026-11-04T13:15:00Z');
const at = release - 2*3600000;
const adp = {kind:'adp',period:'2026-10',value:-25,publishedAt,sourceUrl:'https://adpemploymentreport.com/'};
let records=appendManual([],adp,at-1000);
assert.equal(records[0].value,-25);
assert(validSource('https://mediacenter.adp.com/report','adp'));
assert(!validSource('https://adp.com.evil.test/report','adp'));
assert(!validSource('https://eviladp.com/report','adp'));
assert(!validSource('javascript:alert(1)','adp'));
assert(!validSource('https://me:password@adp.com/report','adp'));
assert(!validSource('https://adp.com/report','ismServices'));
assert.throws(()=>appendManual(records,{...adp,publishedAt:at+1},at));
assert.throws(()=>appendManual(records,{...adp,value:NaN},at));
const ism={kind:'ismServices',period:'2026-10',value:49.5,publishedAt,sourceUrl:'https://www.ismworld.org/report'};
assert.throws(()=>appendManual(records,{...ism,value:101},at));
assert.throws(()=>appendManual(records,{...ism,value:-1},at));
records=appendManual(records,ism,at);
assert(manualSummary(records,'2026-10',cutoff).evidence.find(e=>e.key==='ismServices').text.includes('kontraksi'));
assert.equal(manualSummary(records,'2026-09',cutoff).evidence.length,0);
assert.equal(manualSummary(records,undefined,cutoff).evidence.length,0);
const original=selectManual(records,'adp','2026-10',cutoff);
records=appendManual(records,{...adp,value:100},cutoff+1);
assert.equal(selectManual(records,'adp','2026-10',cutoff).value,-25);
assert.equal(selectManual(records,'adp','2026-10',cutoff+1).value,100);
// Backdating publishedAt cannot backdate when the device learned a correction.
assert.equal(manualSummary(records,'2026-10',cutoff).evidence.find(e=>e.key==='adp').text.includes('-25'),true);
assert.equal(readManual(JSON.stringify(records)).length,3);
assert.throws(()=>readManual(JSON.stringify([original,original])));
const sameTime=appendManual(appendManual([],adp,at),{...adp,value:123},at);
assert.equal(selectManual(sameTime,'adp','2026-10',at).value,123);
const cache={version:1,fetchedAt:at,data:{payroll:[{period:'2026-09',change:100}],unemployment:[],jolts:[],cpi:[],ppi:[]}};
const plan={release,targetMonth:'2026-10',forecast:130,source:'Test',at};
const eligible=records.filter(r=>r.recordedAt<=at);
const snapshot=createSnapshot(cache,plan,at,eligible);
assert.equal(snapshot.manual.length,2);
assert(snapshot.review.evidence.some(e=>e.key==='adp'));
eligible[0].value=80;
assert.equal(snapshot.manual[0].value,49.5);
assert.deepEqual(readHistory(JSON.stringify([snapshot])),[snapshot]);
const backup={version:1,plan,cache,history:[snapshot],manual:records};
assert.deepEqual(parseBackup(backup),backup);
assert.throws(()=>parseBackup({...backup,manual:null}));
assert.equal(reviewFundamentals(cache,plan,at,records).evidence.filter(e=>e.key==='adp').length,1);
const values=new Map();
const store={async getItem(k){return values.get(k)??null},async setItem(k,v){values.set(k,v)},async removeItem(k){values.delete(k)},async multiSet(rows){rows.forEach(([k,v])=>values.set(k,v));}};
(async()=>{
 await restoreLocal(store,backup);
 assert.deepEqual(readManual(values.get(MANUAL_KEY)),records);
 const legacy={version:1,plan:null,cache:null,history:[]};
 await restoreLocal(store,legacy);
 assert.deepEqual(readManual(values.get(MANUAL_KEY)),[]);
 console.log('Passed: ADP/ISM units, official URL validation, timestamp cutoff, append-only corrections, immutable snapshots and backup migration.');
})().catch(e=>{console.error(e);process.exitCode=1});
